def build_system_prompt(role: str | None = None) -> str:
    """构建系统提示词文本。

    返回稳定的身份/职责说明；若字典已预热则追加分类/优先级/状态映射；
    并按当前角色追加能力边界与开场引导、职责外拒答与安全防护规则。
    HITL（人工确认）由工具内部 interrupt 控制，提示词不写任何确认/复述指令。
    role 来自 api 层透传的业务角色编码（REPORTER/HANDLER/SUPERVISOR/ADMIN）。
    """
    parts = [
        _IDENTITY_SECTION,
        "回复使用简体中文，简洁务实；优先使用提供的工具完成任务，关键信息缺失时主动向用户追问。",
    ]
    mapping = dict_service.to_prompt_text()
    if mapping:
        parts.append(mapping)
        parts.append(
            "调用工具时，分类/优先级/状态字段请优先使用上面对应的数字 id"
            "（也可直接传中文标签，系统会自动转换）。"
        )
    parts.append(_role_section(role))
    parts.append(_ENRICH_SECTION)
    parts.append(_REFUSAL_SECTION)
    parts.append(_SECURITY_SECTION)
    return "\n".join(parts)
